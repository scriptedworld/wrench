#!/usr/bin/env python3
"""Generate the Go and Python packs' compiled-in copy of the shipped schemas.

The directory is read here because neither compiler can read one, which is what
FR-3.7 asks for and FR-3.5 permits. Rust needs none of it: `rust/build.rs` runs
every build, so its copy cannot be stale.

    generate-shipped.py            write the generated files
    generate-shipped.py --check    exit 1 if any is stale, and say which

The generated files are committed, so `--check` in the gate is the only thing
standing between them and the drift FR-3.2 exists to prevent. It compares bytes
against a fresh run, catching an edited schema, an added one, a removed one and
a hand-edited generated file alike.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "schemas"
SUFFIX = ".schema.json"

BANNER = "Generated by bin/generate-shipped.py from schemas/. Do not edit."

# The widest escaped literal a chunk may reach, leaving room for the deepest
# indent either generated file uses and for Go's trailing ` +`. Ruff caps a
# Python line at 150.
WIDTH = 110


def shipped() -> list[tuple[str, str]]:
    """Every shipped schema as (filename, exact text), sorted by filename.

    Sorted so the generated files are reproducible: an unsorted directory read
    would rewrite them in a different order on another machine and the check
    would fail on nothing.
    """
    found = sorted(p for p in SCHEMA_DIR.glob("*" + SUFFIX))
    if not found:
        raise SystemExit(f"{SCHEMA_DIR} holds no schemas, so every pack would ship none")

    out = []
    for path in found:
        text = path.read_text()
        document = json.loads(text)
        declared = document.get("$id")
        if not isinstance(declared, str) or not declared:
            raise SystemExit(f"{path.name} declares no $id, so nothing can reference it")
        out.append((path.name, text))
    return out


def literal(text: str) -> str:
    """A Go interpreted string literal for `text`.

    JSON's escaping is accepted verbatim by Go's, so one encoder serves and Go's
    quoting rules are not reimplemented here.
    """
    return json.dumps(text)


def py_literal(text: str) -> str:
    """A Python string literal for `text`, quoted the way ruff wants it.

    The delimiter is whichever quote needs fewer escapes, which is what Q003
    asks for and what `ruff format` rewrites a file to. A schema is mostly
    double quotes, so most chunks take single ones; a chunk holding an
    apostrophe as well takes whichever kind it holds less of, and the
    double-quote default settles a tie.
    """
    body = json.dumps(text)[1:-1]
    if text.count('"') > text.count("'"):
        return "'" + body.replace('\\"', '"').replace("'", "\\'") + "'"
    return '"' + body + '"'


def pieces(text: str) -> list[str]:
    """`text` as chunks that concatenate back to it exactly, one per source line
    in the generated file.

    A schema on one source line runs to thousands of characters, and the shared
    Python standard caps a line at 150 with no exemption for a generated file.
    Chunking is by the width of the escaped form, because escaping grows a
    string and a chunk measured before it would still overrun.

    A chunk also ends at a newline, so the generated file breaks where the
    schema does wherever the schema's own lines are short enough. The longest is
    370 characters, which is why breaking there alone will not do.
    """
    out: list[str] = []
    current: list[str] = []
    width = 2  # the enclosing quotes

    for char in text:
        escaped = literal(char)[1:-1]
        if current and width + len(escaped) > WIDTH:
            out.append("".join(current))
            current, width = [], 2
        current.append(char)
        width += len(escaped)
        if char == "\n":
            out.append("".join(current))
            current, width = [], 2

    if current:
        out.append("".join(current))
    return out


def go_source(entries: list[tuple[str, str]]) -> str:
    body = ""
    for name, text in entries:
        joined = " +\n\t\t\t".join(literal(chunk) for chunk in pieces(text))
        body += f"\t{{\n\t\t{literal(name)},\n\t\t{joined},\n\t}},\n"
    return (
        f"// {BANNER}\n\n"
        "package wrench\n\n"
        "// shippedSchema is one schema as it sits in schemas/, carried as source so\n"
        "// the pack links a single static binary and needs no file at run time.\n"
        "type shippedSchema struct {\n"
        "\tName string\n"
        "\tText string\n"
        "}\n\n"
        "// shippedSchemas is the whole directory, in filename order.\n"
        "var shippedSchemas = []shippedSchema{\n"
        f"{body}"
        "}\n"
    )


def python_source(entries: list[tuple[str, str]]) -> str:
    body = ""
    for name, text in entries:
        joined = "\n        ".join(py_literal(chunk) for chunk in pieces(text))
        body += f"    {py_literal(name)}: (\n        {joined}\n    ),\n"
    return (
        f'"""{BANNER}\n\n'
        "Every shipped schema as its exact text, keyed by filename and in filename\n"
        "order. Carried as source so the pack resolves the schemas without knowing\n"
        "where it was installed.\n"
        '"""\n\n'
        "SHIPPED: dict[str, str] = {\n"
        f"{body}"
        "}\n"
    )


TARGETS = [
    (ROOT / "shipped_gen.go", go_source),
    (ROOT / "python" / "wrench" / "_shipped.py", python_source),
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report staleness and change nothing",
    )
    args = parser.parse_args()

    entries = shipped()
    stale = []
    for path, render in TARGETS:
        wanted = render(entries)
        current = path.read_text() if path.exists() else None
        if current == wanted:
            continue
        if args.check:
            stale.append(path)
            continue
        path.write_text(wanted)
        print(f"wrote {path.relative_to(ROOT)}")

    if args.check:
        for path in stale:
            print(f"STALE  {path.relative_to(ROOT)}")
        if stale:
            print(f"\n{len(stale)} generated file(s) do not match schemas/.")
            print("Run bin/generate-shipped.py and commit the result.")
            return 1
        names = ", ".join(name for name, _ in entries)
        print(f"{len(entries)} schema(s) compiled into every pack: {names}")
        return 0

    print(f"{len(entries)} schema(s) from {SCHEMA_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
