/**
 * Generate `src/shipped.ts` from the repository's `schemas/` directory.
 *
 *     npm run shipped            write it
 *     npm run shipped:check      fail when it is stale, naming the file
 *
 * A pack discovers the schemas by reading the directory (FR-3.7), never from a
 * list of filenames a person maintains. TypeScript cannot read a directory at
 * compile time any more than the other packs' compilers can, so the reading
 * happens here and the result is committed, exactly as Go's and Python's do.
 *
 * The committed copy is the cost, and it is the drift FR-3.2 exists to prevent.
 * What holds it current is `--check`, run by this pack's own suite rather than
 * by a gate task: a check inside the suite fails wherever the suite runs, and
 * needs nothing added to a jig that three other sessions are working in.
 *
 * The target is excluded from `prettier` in `.prettierignore`, and that is what
 * makes the two checks agree. A formatter breaks a long string literal onto its
 * own line and rewrites its quoting, so a formatted copy is never what this
 * writes and `--check` would call a current file stale. Teaching the generator
 * to reproduce the formatter's output would pin the pack to a formatter
 * version.
 *
 * Written over `node:fs/promises` and `node:process` rather than any one
 * runtime's own namespace, so the same file runs under Node and under Deno.
 */

import { readFile, readdir, writeFile } from "node:fs/promises";
import process from "node:process";

const HERE = new URL(".", import.meta.url);
const SCHEMA_DIR = new URL("../../schemas/", HERE);
const TARGET = new URL("../src/shipped.ts", HERE);

const HEADER = `/**
 * The shipped schemas, as the bytes in \`schemas/\` (FR-3.2, FR-3.5).
 *
 * GENERATED by \`bin/generate_shipped.ts\` from that directory. Do not edit: a
 * change belongs in the schema, and this file is how it reaches the pack.
 *
 * The text is carried rather than the parsed object, so the suite can hold
 * these bytes against the directory and name the file when they differ.
 */

export const SHIPPED: Readonly<Record<string, string>> = {
`;

/** Every shipped schema, keyed by filename, read from the directory. */
async function fromDirectory(): Promise<Map<string, string>> {
  const names: string[] = [];
  for (const entry of await readdir(SCHEMA_DIR, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".schema.json")) {
      names.push(entry.name);
    }
  }
  if (names.length === 0) {
    throw new Error(`${SCHEMA_DIR.pathname} holds no schemas`);
  }
  const out = new Map<string, string>();
  for (const name of names.sort()) {
    const text = await readFile(new URL(name, SCHEMA_DIR), "utf8");
    const declared = (JSON.parse(text) as { $id?: unknown }).$id;
    if (typeof declared !== "string" || declared === "") {
      throw new Error(`${name} declares no $id, so nothing can reference it`);
    }
    out.set(name, text);
  }
  return out;
}

/** The file those schemas make. */
export function rendered(schemas: Map<string, string>): string {
  const rows = [...schemas].map(
    ([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`,
  );
  return `${HEADER}${rows.join("\n")}\n};\n`;
}

/** What is on disk now, or "" where nothing is. */
async function current(): Promise<string> {
  try {
    return await readFile(TARGET, "utf8");
  } catch {
    return "";
  }
}

if (import.meta.main) {
  const check = process.argv.slice(2).includes("--check");
  const wanted = rendered(await fromDirectory());
  if (!check) {
    await writeFile(TARGET, wanted);
    console.log(`wrote ${TARGET.pathname}`);
  } else if ((await current()) !== wanted) {
    console.error(
      `${TARGET.pathname} is stale: run \`npm run shipped\` after changing schemas/`,
    );
    // The exit code rather than `process.exit`, so anything still buffered on
    // stderr is written before the process goes.
    process.exitCode = 1;
  } else {
    console.log(`${TARGET.pathname} is current`);
  }
}
